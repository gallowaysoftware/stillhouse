// Anonymised cross-tenant benchmarks. PLAN J2.
//
// Every other read in Stillhouse is bounded by row-level security: a
// licensee sees its own rows and nothing else. This one deliberately
// reaches across that line, which makes it the single place where getting
// the privacy wrong publishes one distillery's operations to its
// competitors.
//
// Four rules, and the service refuses rather than bends any of them:
//
//   Opt-in, off by default and never inferred.
//   Reciprocity — only a participant may read. A reader who contributes
//     nothing is a data tap, not a network.
//   A k-anonymity floor counted in distinct LICENSEES, not measurements:
//     one distillery with four hundred casks is still one distillery.
//   Dominance suppression — if one participant supplies most of the
//     sample, the cohort figure is theirs with a label on it.
//
// And what comes back is quartiles. Never a maximum: a maximum IS one
// participant's exact number.

