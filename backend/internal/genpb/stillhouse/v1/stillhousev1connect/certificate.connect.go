// Certificates of age and origin.
//
// EDM3-1-1 ¶43–46: several trading partners require a certificate signed
// by a Canadian official attesting the age and origin of exported
// spirits. Age runs from original warehousing in small wood to removal
// for export sale, and resets on redistillation.
//
// Stillhouse already holds the maturation clock, so what is missing is
// the packet that reads it — and, more to the point, the honesty about
// what it can and cannot attest. Stillhouse does not sign anything: it
// assembles the evidence, states the age it can support and where that
// figure came from, and names every cask it could not account for. A
// certificate that quietly rounded up over a gap in the record is the one
// failure mode that matters here.

