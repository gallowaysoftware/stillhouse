// Who the alcohol went to.
//
// Stillhouse had no customer concept: a removal named its destination in
// free text, so the same provincial board appeared under three spellings
// across three months of returns and nothing could be totalled by buyer.
// Worse, the destination *kind* — which decides whether duty is charged
// and which B266 line the movement lands on — was re-chosen by hand each
// time, next to free text that did not have to agree with it.
//
// A customer fixes the classification where the decision belongs. The
// LCBO is a provincial board and always will be; a removal to them
// cannot be typed as an export by accident.

