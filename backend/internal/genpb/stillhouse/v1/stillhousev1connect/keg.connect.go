// The keg register. PLAN D5.
//
// The distinction this file holds is between the VESSEL and its CONTENTS.
// A keg's spirits are already recorded elsewhere, and their volume,
// strength, LAA and duty reach the B266 from there. A keg carries none of
// those figures — it points at the row that owns them. Putting volume_l
// and abv_pct on a keg is the obvious design and it puts the same alcohol
// on a filed return twice.
//
// Which row it points at follows from the keg's size, and the threshold
// is the Act's rather than ours: a marked special container under
// EDM3-8-1 is 100 to 1500 litres. Spirits in anything smaller are
// packaged exactly as a bottle is — a 50 L keg is a large bottle as far
// as the Act is concerned — so its contents are a packaged lot.
//
// What the register adds is what nothing else knows: where the physical
// asset is, what deposit is outstanding on it, and how long its contents
// have been sitting.

