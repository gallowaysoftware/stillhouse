// Barcodes for a rackhouse.
//
// Finding cask 0417 by scrolling a list is not how a rackhouse is
// operated. What is operated is: a tag on the bung stave, a label on the
// case, and a wedge scanner that behaves like a keyboard. That needs two
// things Stillhouse did not have — something short enough to print and
// scan on every row, and one place that turns whatever came off the
// scanner back into the row it names.
//
// The code is derived from the row's id rather than stored: 14
// characters, a kind letter and 13 base-32 digits. Nothing to generate,
// nothing to backfill, and every cask that has ever existed has one from
// the moment this ships. See backend/internal/labelcode.

