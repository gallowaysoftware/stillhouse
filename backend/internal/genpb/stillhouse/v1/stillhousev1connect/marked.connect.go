// Marked special containers.
//
// EDM3-8-1: a container of 100 to 1,500 litres, marked rather than
// stamped, for delivery to a registered user or to bottle-your-own
// premises. They are packaging — the alcohol has left bulk — and they
// have their own lines on the B266 and the B262. Stage 143 split the
// packaging figures by duty treatment and left the third column of that
// line, "packaged in marked special containers", with nothing that could
// write it.
//
// What Stillhouse does not do is decide what the mark has to say. The
// marking requirements are EDM3-8-1's and are the licensee's to satisfy;
// the field records what was applied so an auditor can see it, and
// nothing is generated. No excise stamp is drawn either: these are
// marked, which is the whole distinction, and a licensee whose
// circumstances differ will see that no stamp was consumed rather than
// discovering a silent one.

