// Tasting-room and web sales, arriving as data rather than as typing.
// PLAN G4.
//
// This is a compliance feature wearing a sales costume: every sale keyed
// by hand is a chance to under-report. Automating it introduces the
// opposite failure, and that is the one this service is shaped around — a
// POS webhook is delivered at least once, and a retry that creates a
// second removal reports duty twice and takes stock off the shelf that is
// still on it.
//
// So ingest is idempotent on the POS's own line id, and a sale whose SKU
// nobody has mapped is REJECTED and kept rather than dropped. A sale that
// vanishes because of a missing mapping is exactly the under-reporting
// this feature exists to prevent, arriving through the door it opened.

