// Provincial reporting: the shape, before the content.
//
// Every province a licensee sells into wants something reported, and no
// two want the same thing on the same clock. What Stillhouse can build
// without a source in front of it is the machinery — which jurisdictions
// the licensee is registered in, what each expects, when it is due, and
// what the figures are.
//
// What it must not do is ship a table of other people's filing deadlines
// from memory. A definition is entered by the licensee or their
// consultant and carries the citation it came from, the same discipline
// the pricing rates follow. The distinction matters more here than
// anywhere else: a wrong excise figure is caught by CRA, and a wrong
// provincial deadline is caught by a delisting.

