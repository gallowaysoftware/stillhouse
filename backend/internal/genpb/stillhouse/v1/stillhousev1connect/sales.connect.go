// The order, the pick and the removal it becomes.
//
// Removals were recorded by hand: somebody shipped a pallet, and later
// somebody else remembered to type a removal against the right lot. The
// two acts had nothing to do with each other, so a shipment that never
// got typed was a quiet under-report on the return, and a removal typed
// against the wrong lot moved duty between jurisdictions with nothing to
// catch it.
//
// Here a shipment produces the removals. Marking one shipped writes them
// in the same transaction, against the lots that were actually picked —
// what left the building and what the return says left are the same rows
// read twice.

