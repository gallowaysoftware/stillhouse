// What needs making, and whether the plant can make it.
//
// Driven by actual demand — confirmed, unshipped order lines — rather
// than by a forecast. Stillhouse has no forecast, and a plan built on an
// invented one looks exactly as authoritative as a plan built on orders.
// PLAN F7 is where a forecast would go; until it exists this says what it
// is working from, on the page, every time.
//
// The other half of honesty here is the plant. A piece of equipment with
// no recorded capacity or no recorded run time cannot be planned against,
// and is returned with the reason rather than dropped — an empty schedule
// and a schedule that silently omitted half the still house look
// identical from the outside.

