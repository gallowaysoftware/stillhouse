// What a second person needs.
//
// Stillhouse recorded what had happened and never what was going to.
// That works for an owner-operator holding the plan in their head, and
// stops working the day somebody else walks in — because "what should I
// be doing" has no answer in the system.
//
// A work order is deliberately thin: an intention with a subject, an
// owner and a date. Not a second copy of the production record. The
// temptation is to have it hold quantities and reconcile them against
// what happened, and that way there are two sources of truth for one
// batch and the trusted one is whichever was typed into last.

